"""
Pydantic v2 data models for the Memory subsystem.
Covers MessageRole, ChatMessage, SessionContext, FactTriple, and EpisodicRecord.
Conforms to interface contracts specified in PROJECT.md and explorer survey handoff.
"""

from __future__ import annotations
import time
from datetime import datetime
from enum import Enum
from typing import Dict, Any, Optional, List, Union
from pydantic import BaseModel, Field, ConfigDict


class MessageRole(str, Enum):
    """Canonical role of a participant in a conversation turn."""
    SYSTEM = "system"
    USER = "user"
    ASSISTANT = "assistant"
    TOOL = "tool"


class ChatMessage(BaseModel):
    """
    Individual turn in a session conversation stream.
    Supports role, content, tool call attachments, pinned protection from eviction,
    and cached token counts.
    """
    model_config = ConfigDict(extra="ignore")

    role: MessageRole
    content: str
    name: Optional[str] = Field(default=None, description="Identifier of the specific agent or tool")
    tool_call_id: Optional[str] = Field(default=None, description="Matching ID for tool response messages")
    tool_calls: Optional[List[Dict[str, Any]]] = Field(default=None, description="Tool invocation requests emitted by assistant")
    pinned: bool = Field(default=False, description="Guaranteed protection against sliding window eviction")
    token_count: int = Field(default=0, description="Cached or precomputed token length")
    timestamp: Union[float, datetime, str] = Field(default_factory=time.time, description="Timestamp of message creation")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Arbitrary execution context metadata")


class SessionContext(BaseModel):
    """
    Ephemeral working context holding messages, active goals, scratchpad variables,
    and rolling summary of pruned messages.
    """
    model_config = ConfigDict(extra="ignore")

    session_id: str
    user_id: str = Field(default="default_user", description="Owner user identifier")
    active_intent: Optional[str] = Field(default=None, description="Currently detected intent or goal")
    scratchpad: Dict[str, Any] = Field(default_factory=dict, description="Temporary variables and intermediate outputs")
    messages: List[ChatMessage] = Field(default_factory=list, description="Ordered conversation turn history")
    rolling_summary: Optional[str] = Field(default=None, description="Accumulated digest of evicted conversation turns")
    max_token_budget: int = Field(default=4096, description="Upper bound for sliding window token capacity")
    created_at: Union[float, datetime, str] = Field(default_factory=time.time)
    updated_at: Union[float, datetime, str] = Field(default_factory=time.time)


class FactTriple(BaseModel):
    """
    Discrete atomic fact or preference attribute stored in persistent long-term memory.
    Structured as (Subject, Predicate, Object) within a domain namespace.
    """
    model_config = ConfigDict(extra="ignore")

    id: Optional[int] = Field(default=None, description="Primary key generated by SQLite store")
    namespace: str = Field(default="user", description="Classification scope: user | project | domain | rule")
    subject: str = Field(..., description="Entity name or concept, e.g. 'Филипп', 'Deckor'")
    predicate: str = Field(..., description="Attribute or relationship, e.g. 'формат_работы', 'стек'")
    object_value: str = Field(..., description="Value or assertion, e.g. 'СТРОГО УДАЛЁНКА', 'FastAPI, Docker'")
    confidence: float = Field(default=1.0, ge=0.0, le=1.0, description="Truth certainty score [0.0, 1.0]")
    source_citation: Optional[str] = Field(default=None, description="Provenance reference: file, session, or turn")
    tags: List[str] = Field(default_factory=list, description="Categorization or search tags")
    version: int = Field(default=1, ge=1, description="Fact revision version number")
    ttl_days: Optional[int] = Field(default=None, ge=1, description="Time-to-live in days")
    expires_at: Optional[Union[str, datetime]] = Field(default=None, description="Expiration timestamp (YYYY-MM-DD HH:MM:SS)")
    is_deleted: bool = Field(default=False, description="Soft deletion flag")
    created_at: Union[float, datetime, str] = Field(default_factory=time.time)

    def format_fact(self) -> str:
        """Format fact triple into human-readable string."""
        return f"({self.namespace}) {self.subject} {self.predicate}: {self.object_value}"


class EpisodicRecord(BaseModel):
    """
    Persistent record of a completed agent execution task.
    Enables procedural learning and retrieval of past execution plans and error patterns.
    """
    model_config = ConfigDict(extra="ignore")

    episode_id: str = Field(..., description="Unique episode identifier")
    task_goal: str = Field(..., description="Original goal or prompt describing the task")
    plan_executed: List[str] = Field(default_factory=list, description="Ordered list of executed subtasks or steps")
    outcome: str = Field(..., description="Execution outcome: success | failed | partially_completed")
    tools_used: List[str] = Field(default_factory=list, description="Names of tools called during the episode")
    lessons_learned: Optional[str] = Field(default=None, description="Key insights, pitfalls, or optimizations")
    error_signature: Optional[str] = Field(default=None, description="Error classification or stack trace summary")
    timestamp: Union[float, datetime, str] = Field(default_factory=time.time)
